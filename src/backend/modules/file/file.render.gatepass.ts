import path from 'node:path';
import { readFileSync } from 'node:fs';
import PDFDocument from 'pdfkit';
import { LogSource } from '../../core/logging/log-sources.js';
import type { Logger, ScopedLogger } from '../../core/logging/logger.js';
import type { Cell } from '../emandi/emandi.types.js';
import type { GatepassPayload } from './file.types.js';
import { assetsDir } from '../../paths.js';

export class GatepassRenderer {
  private readonly margin = 36;
  private readonly logo: string = `data:image/png;base64,${readFileSync(path.join(assetsDir, 'logo_emandi.png')).toString('base64')}`;
  private readonly regularFont: Buffer = readFileSync(path.join(assetsDir, 'kripa-regular.ttf'));
  private readonly boldFont: Buffer = readFileSync(path.join(assetsDir, 'kripa-semibold.ttf'));
  private readonly paddingY = 5;
  private readonly logger: ScopedLogger;

  constructor({ logger }: { logger: Logger }) {
    this.logger = logger.for(LogSource.File);
  }

  generate = async (payload: GatepassPayload): Promise<Buffer> => this.generatePdf((document) => this.render(document, payload));

  private render = (document: PDFKit.PDFDocument, payload: GatepassPayload): void => {
    const { width, y } = this.drawHeader(document, payload);
    let nextY = this.drawTable(document, this.infoRows(payload), this.margin, y, this.scale([12, 12, 19, 19, 19, 19], width)) + 12;
    nextY = this.drawTable(document, [
      [this.header('गेटपास प्राप्त कर्ता फर्म का नाम व पता'), this.header('परिवहन का साधन और वाहन संख्या'), this.header('निर्दिष्ट कृषि उत्पादन का विवरण'), this.header('क्रेता फर्म का नाम व पता'), this.header('क्रेता व्यापारी से संबंधित मंडी समिति का नाम')],
      [this.value(payload.trader_name), this.value(`${payload.vehicle}\n${payload.vehicle_no}`), { nested: [['नाम', 'किस्म', 'बण्डल की संख्या', 'वजन', 'माप'], [payload.crop_name_hi, payload.crop_type, payload.bundle_no, payload.crop_weight, payload.qty_parameter || '']] }, this.value(payload.kreta_mandiName || payload.kreta_mandi), this.value('')]
    ], this.margin, nextY, this.scale([175, 80, 245, 180, 70], width));
    nextY += 12;
    nextY = this.drawTable(document, [[this.label('Latitude'), this.value(payload.latitude), this.label('Longitude'), this.value(payload.longitude), this.label('टैगिंग का दिनांक'), this.value(payload.taggingDate), this.label('वाहन संख्या'), this.value(payload.vehicle_no)]], this.margin, nextY, this.scale([1, 1, 1, 1, 1, 1, 1, 1], width));
    nextY += 12;
    nextY = this.drawTable(document, [[this.label('गंतव्य स्थान पर पहुँचने का अनुमानित समय'), { parts: [payload.dateofdestination, `(अनुमानित समय - ${payload.estimated_travel_time}) (औसत गति - ${payload.avg_speed} क.मी / घंटा)`], bold: true }]], this.margin, nextY, this.scale([2, 5], width));
    const labelY = nextY + 14;
    this.drawAutoGeneratedLabel(document, labelY);
    this.drawContentBorder(document, labelY + 28);
  };

  private drawHeader = (document: PDFKit.PDFDocument, payload: GatepassPayload): { width: number; y: number } => {
    const width = document.page.width - this.margin * 2;
    const imageSize = 90;
    const textX = this.margin + imageSize + 10;
    const textWidth = width - 2 * (imageSize + 10);
    document.rect(6, 6, document.page.width - 12, document.page.height - 12).lineWidth(0.6).strokeColor('#000').stroke();
    document.image(this.logo, this.margin, this.margin, { fit: [imageSize, imageSize] });
    document.image(this.qrDataUrl(payload.qr), document.page.width - this.margin - imageSize, this.margin, { fit: [imageSize, imageSize] });
    const heading = 'कृषि उत्पादन मंडी समिति ';
    const headingWidth = document.font('KripaRegular').fontSize(11).widthOfString(heading);
    const mandi = 'सादाबाद';
    const mandiWidth = document.font('KripaBold').fontSize(11).widthOfString(mandi);
    const headingX = textX + (textWidth - headingWidth - mandiWidth) / 2;
    document.font('KripaRegular').fontSize(11).text(heading, headingX, this.margin, { lineBreak: false });
    document.font('KripaBold').fontSize(11).text(mandi, headingX + headingWidth, this.margin, { lineBreak: false });
    document.font('KripaRegular').fontSize(11).text('[ प्रपत्र संख्या-5 (क) ]', textX, this.margin + 18, { width: textWidth, align: 'center' });
    document.font('KripaRegular').fontSize(11).text('गेटपास', textX, this.margin + 36, { width: textWidth, align: 'center' });
    return { width, y: this.margin + imageSize + 4 };
  };

  private infoRows = (payload: GatepassPayload): Cell[][] => {
    const values: Array<[string, string | null | undefined]> = [
      ['पुस्तक संख्या', payload.book_number], ['गेटपास संख्या', payload.serial_number], ['आवेदन संख्या (यूनिक कोड)', payload.uniquecode],
      ['जारी करने का दिनांक', payload.dateofissue], ['जारी करने का समय', payload.timeofissue], ['संलग्न प्रपत्र-9 की संख्या', payload.nine_r_id],
      ['दिनांक', this.formatDate(payload.dateofissue)], ['गंतव्य की दूरी (KM)', payload.dist_todestination], ['सीमांत गढ़ केंद्र का नाम', payload.home_center],
      ['कोड', payload.center_code], ['उत्पाद का नाम', `${payload.crop_name_hi} (${payload.crop_name})`], ['वजन (कुंतल में)', payload.crop_weight]
    ];
    const rows: Cell[][] = [];
    for (let index = 0; index < values.length; index += 3) rows.push(values.slice(index, index + 3).flatMap(([label, value]) => [this.label(label), this.value(value)]));
    return rows;
  };

  private drawAutoGeneratedLabel = (document: PDFKit.PDFDocument, y: number): void => { document.font('KripaBold').fontSize(9.5).fillColor('#ff0000').text('Auto Generated Gatepass', this.margin, y, { width: document.page.width - this.margin * 2 }); };

  private drawContentBorder = (document: PDFKit.PDFDocument, bottom: number): void => {
    document.rect(12, 12, document.page.width - 24, bottom - 12).lineWidth(0.6).strokeColor('#ff0000').stroke();
  };

  private drawTable = (document: PDFKit.PDFDocument, rows: Cell[][], x: number, y: number, widths: number[]): number => {
    rows.forEach((row) => {
      let column = 0;
      const laidOut = row.map((cell) => { const span = cell.span || 1; const width = widths.slice(column, column + span).reduce((sum, value) => sum + value, 0); const result = { cell, x: x + widths.slice(0, column).reduce((sum, value) => sum + value, 0), width }; column += span; return result; });
      const height = Math.max(...laidOut.map(({ cell, width }) => this.cellHeight(document, cell, width)));
      laidOut.forEach(({ cell, x: cellX, width }) => this.drawCell(document, cell, cellX, y, width, height));
      y += height;
    });
    return y;
  };

  private drawCell = (document: PDFKit.PDFDocument, cell: Cell, x: number, y: number, width: number, height: number): void => {
    if (cell.fill) document.save().fillColor(cell.fill).rect(x, y, width, height).fill().restore();
    document.rect(x, y, width, height).lineWidth(0.6).strokeColor('#6F6D6D').stroke();
    if (cell.nested) return void this.drawNested(document, cell.nested, x, y, width, height);
    if (cell.parts) {
      let textY = y + this.paddingY;
      cell.parts.forEach((part, index) => {
        document.font(index ? 'KripaRegular' : 'KripaBold').fontSize(9.5).text(part, x + 2, textY, { width: width - 4, align: 'left' });
        textY += document.heightOfString(part, { width: width - 4 }) + 2;
      });
      return;
    }
    const text = cell.text || '';
    const textWidth = width - 4;
    document.font(cell.bold ? 'KripaBold' : 'KripaRegular').fontSize(cell.size || 9.5);
    const textHeight = cell.valign === 'center' ? document.heightOfString(text, { width: textWidth }) : 0;
    const textY = cell.valign === 'center'
      ? y + Math.max(this.paddingY, (height - textHeight) / 2)
      : y + this.paddingY;
    document.text(text, x + 2, textY, { width: textWidth, align: cell.align || 'left' });
  };

  private drawNested = (document: PDFKit.PDFDocument, rows: string[][], x: number, y: number, width: number, height: number): void => {
    const columnWidths = this.scale([0.75, 0.85, 1.8, 0.85, 0.75], width);
    const rowHeight = height / rows.length;
    rows.forEach((row, rowIndex) => row.forEach((text, column) => {
      const cellX = x + columnWidths.slice(0, column).reduce((sum, value) => sum + value, 0);
      const columnWidth = columnWidths[column] || 0;
      const cellY = y + rowIndex * rowHeight;
      if (column || rowIndex) document.moveTo(cellX, y).lineTo(cellX, y + height).lineWidth(0.6).strokeColor('#6F6D6D').stroke();
      if (rowIndex) document.moveTo(x, cellY).lineTo(x + width, cellY).lineWidth(0.6).strokeColor('#6F6D6D').stroke();
      const textWidth = columnWidth - 4;
      document.font('KripaBold').fontSize(9.5);
      const textHeight = document.heightOfString(text, { width: textWidth });
      const textY = cellY + Math.max(this.paddingY, (rowHeight - textHeight) / 2);
      document.text(text, cellX + 2, textY, { width: textWidth, align: 'left', lineBreak: false });
    }));
  };

  private cellHeight = (document: PDFKit.PDFDocument, cell: Cell, width: number): number => {
    if (cell.nested) return Math.max(48, cell.nested.length * 26);
    document.font(cell.bold ? 'KripaBold' : 'KripaRegular').fontSize(cell.size || 9.5);
    if (cell.parts) return cell.parts.reduce((height, part) => height + document.heightOfString(part, { width: width - 4 }) + 2, 2 * this.paddingY);
    return document.heightOfString(cell.text || '', { width: width - 4 }) + 2 * this.paddingY;
  };
  private label = (text: string): Cell => ({ text, align: 'left' });
  private value = (text: string | null | undefined): Cell => ({ text: text || '', bold: true, align: 'left' });
  private header = (text: string, span?: number): Cell => ({ text, ...(span ? { span } : {}), bold: true, align: 'left', valign: 'center', fill: '#fafafa', size: 9.5 });
  private center = (text: string | undefined): Cell => ({ text: text || '', bold: true, align: 'left' });
  private scale = (values: number[], width: number): number[] => { const factor = width / values.reduce((sum, value) => sum + value, 0); return values.map((value) => value * factor); };
  private qrDataUrl = (value: string): string => `data:image/png;base64,${(value.split(',')[1] || value).replace(/\s/g, '')}`;
  private formatDate = (value: string): string => { const match = value.match(/^(\d{4})-(\d{2})-(\d{2})/); return match ? `${match[3]}/${match[2]}/${match[1]}` : value; };

  private generatePdf = async (draw: (document: PDFKit.PDFDocument) => void): Promise<Buffer> => {
    this.logger.info('Rendering Gatepass Pdf...');
    const document = new PDFDocument({ size: 'A4', layout: 'landscape', margin: this.margin });
    document.registerFont('KripaRegular', this.regularFont);
    document.registerFont('KripaBold', this.boldFont);
    const chunks: Buffer[] = [];
    document.on('data', (chunk: Buffer) => chunks.push(chunk));
    const completed = new Promise<Buffer>((resolve, reject) => { document.on('end', () => resolve(Buffer.concat(chunks))); document.on('error', reject); });
    draw(document);
    document.addPage();
    draw(document);
    document.end();
    return completed;
  };
}
